import json
import logging
import sys
from pathlib import Path
from typing import List, Optional, Tuple, Union

from tqdm import tqdm

SRC_ROOT = Path(__file__).resolve().parents[2] / "src"
if str(SRC_ROOT) not in sys.path:
    sys.path.append(str(SRC_ROOT))

from data.dataset import ForwardDynamicsDataset, RawSample

logger = logging.getLogger(__name__)

class UnsupervisedVideoEditingDataset(ForwardDynamicsDataset):
    """
    Dataset implementation for Unsupervised Video Frames (UCF, Kinetics, MIT).
    This processes the JSONL files generated by the Liquid IDP inference script.
    
    Structure:
        Input: Image 1 (State t)
        Text:  Predicted Action (Inverse Dynamics)
        Output: Image 2 (State t+1)
    """
    
    def __init__(
        self, 
        base_dir: Union[str, Path], 
        data_file_path: Optional[Union[str, Path]] = None,
        datasets_to_load: List[str] = ["ucf", "kinetics", "mit"],
        min_likelihood: Optional[float] = None
    ):
        """
        Args:
            base_dir: The root directory containing the dataset folders
                      (e.g., datasets/unsupervised-frames-ucf-kinetics-mit).
            data_file_path: Optional. If provided, loads ONLY this specific JSONL file. 
                            If None, loads 'train.jsonl' from all folders in `datasets_to_load`.
            datasets_to_load: List of subfolder names to scan if data_file_path is None.
            min_likelihood: If set (e.g., -2.0), filters out samples with a predicted_likelihood 
                            lower than this value.
        """
        self.base_dir = Path(base_dir)
        self.min_likelihood = min_likelihood
        
        processed_data: List[RawSample] = []
        total_lines_processed = 0

        files_to_process = []
        if data_file_path:
            files_to_process.append(Path(data_file_path))
        else:
            for ds_name in datasets_to_load:
                json_path = self.base_dir / ds_name / "train.jsonl"
                if json_path.exists():
                    files_to_process.append(json_path)
                else:
                    logger.warning(f"Dataset file not found: {json_path}")

        if not files_to_process:
             raise FileNotFoundError(f"No train.jsonl files found in {base_dir} for {datasets_to_load}")

        for json_file in files_to_process:
            data, lines = self._load_single_file(json_file)
            processed_data.extend(data)
            total_lines_processed += lines

        super().__init__(processed_data)
        
        if not processed_data:
            raise ValueError("Dataset is empty after loading and filtering.")
            
        print(f"Loaded {len(processed_data)} samples from {total_lines_processed} lines.")
        if min_likelihood is not None:
            print(f"Applied likelihood filter >= {min_likelihood}")

    def _get_file_line_count(self, file_path: Path) -> int:
        """Utility to quickly count lines for tqdm."""
        with open(file_path, 'r', encoding='utf-8') as f:
            return sum(1 for _ in f)

    def _load_single_file(self, data_file_path: Path) -> Tuple[List[RawSample], int]:
        """
        Parses a single JSONL file and validates paths.
        """
        valid_samples: List[RawSample] = []
        total_lines = self._get_file_line_count(data_file_path)
        
        with open(data_file_path, 'r', encoding='utf-8') as f:
            pbar = tqdm(f, total=total_lines, desc=f"Loading {data_file_path.parent.name}")
            
            for line in pbar:
                try:
                    entry = json.loads(line)
                    
                    rel_input_path = entry.get("input_image_path")
                    rel_output_path = entry.get("output_image_path")
                    textual_action = entry.get("textual_action")
                    likelihood = entry.get("predicted_likelihood")

                    if not (rel_input_path and rel_output_path and textual_action):
                        continue

                    if self.min_likelihood is not None:
                        if likelihood is None or likelihood < self.min_likelihood:
                            continue

                    input_image_path = self.base_dir / rel_input_path
                    output_image_path = self.base_dir / rel_output_path

                    if input_image_path.exists() and output_image_path.exists():
                        valid_samples.append({
                            "input_image_path": input_image_path,
                            "textual_action": textual_action,
                            "output_image_path": output_image_path,
                        })
                    
                except json.JSONDecodeError:
                    continue
                except Exception:
                    continue

        return valid_samples, total_lines

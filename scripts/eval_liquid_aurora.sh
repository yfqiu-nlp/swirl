#!/bin/bash
#SBATCH --job-name=eval-liquid
#SBATCH --nodes=1
#SBATCH --ntasks-per-node=1
#SBATCH --cpus-per-task=64
#SBATCH --mem=512G
#SBATCH --time=150:00:00
#SBATCH --gpus-per-node=8
#SBATCH --output=logs/slurm-%j.out
# #SBATCH --account=YOUR_ACCOUNT
# #SBATCH --qos=YOUR_QOS

# Print job information
echo "=================================="
echo "SLURM Job Information"
echo "=================================="
echo "Job ID: $SLURM_JOB_ID"
echo "Job Name: $SLURM_JOB_NAME"
echo "Nodes: $SLURM_JOB_NUM_NODES"
echo "Tasks per node: $SLURM_NTASKS_PER_NODE"
echo "Total tasks: $SLURM_NTASKS"
echo "Node list: $SLURM_NODELIST"
echo "=================================="

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
export PYTHONPATH="${PYTHONPATH:-}:$REPO_ROOT:$REPO_ROOT/src"
# Optional: set Hugging Face cache locations
# export HF_HOME="${HF_HOME:-$REPO_ROOT/.cache/huggingface}"
# export HF_DATASETS_CACHE="${HF_DATASETS_CACHE:-$HF_HOME/datasets}"
# export HF_HUB_OFFLINE=1

export MASTER_ADDR=$(scontrol show hostnames "$SLURM_JOB_NODELIST" | head -n 1)
export MASTER_PORT=29500
export NCCL_IB_DISABLE=0
export NCCL_SOCKET_IFNAME=^docker0,lo
export NCCL_TREE_THRESHOLD=0

# Activate your environment before running, e.g.:
# source /path/to/conda.sh && conda activate swirl
mkdir -p logs

# -----------------------------------------------------------------------------
# Configuration for Liquid Model
# -----------------------------------------------------------------------------
# Update this to your Liquid checkpoint path

STORAGE_PATH="${STORAGE_PATH:-$REPO_ROOT}"
EXPERIMENT_NAME="Liquid_V1_7B-pico-aurora-multiturn-sft-grpo_fdp_kinetics+ucf+mit_roll8_lr1e6_warmup100_lrScheCosine_beta0.1_bsz32/checkpoint-1100"
# EXPERIMENT_NAME="Liquid_V1_7B-pico-aurora-multiturn-sft-grpo_fdp_kinetics+ucf+mit_roll8_lr1e6_warmup100_lrScheCosine_beta0.1_bsz128/checkpoint-200"
MODEL_PATH="${MODEL_PATH:-$STORAGE_PATH/rlwm-checkpoints/$EXPERIMENT_NAME}"
OUTPUT_DIR="${OUTPUT_DIR:-$REPO_ROOT/outputs/AURORA/$EXPERIMENT_NAME}"

DATASET_ROOT="${DATASET_ROOT:-$STORAGE_PATH/datasets/AURORA}"
GEN_DIR="${GEN_DIR:-$OUTPUT_DIR/gen_image}"
LOG_DIR="${LOG_DIR:-$OUTPUT_DIR/logs}"

# Files are usually test.jsonl in subfolders, but the script handles the mapping
SPLIT_FILE="test.json"

GPT_EVALUATOR="gpt-4o"

TOTAL_NODES=${TOTAL_NODES:-1}
NODE_ID=${NODE_ID:-0}
LOCAL_GPUS=${LOCAL_GPUS:-0,1,2,3,4,5,6,7}
MASTER_NODE=${MASTER_NODE:-0}

mkdir -p "$OUTPUT_DIR" "$GEN_DIR" "$LOG_DIR"

# -----------------------------------------------------------------------------
# Image generation (Using new Liquid Script)
# -----------------------------------------------------------------------------
echo "Starting Liquid inference on Node $NODE_ID..."

python src/evaluation/aurora/aurora_eval.py \
  --model_path "$MODEL_PATH" \
  --dataset_root "$DATASET_ROOT" \
  --output_dir "$GEN_DIR" \
  --devices "$LOCAL_GPUS" \
  --shard_id "$NODE_ID" \
  --total_shards "$TOTAL_NODES" \
  --split_file "$SPLIT_FILE" \
  --vae_path "${VAE_PATH:-$STORAGE_PATH/vision_tokenizers/chameleon/}" \
  --temperature 0.75 \

echo "AURORA generation complete for node $NODE_ID"

# -----------------------------------------------------------------------------
# Evaluation (Identical to Bagel workflow)
# Only master node performs evaluation
# -----------------------------------------------------------------------------
if [[ "$MASTER_NODE" == "$NODE_ID" ]]; then
  echo "Starting Evaluation..."

  # Note: We use the original Bagel evaluation scripts as the folder structure
  # and file names generated by Liquid are identical.

  python src/evaluation/aurora/evaluate_aurora.py \
    --dataset_root "$DATASET_ROOT" \
    --generated_root "$GEN_DIR" \
    --split_file "$SPLIT_FILE" \
    --save_path "$OUTPUT_DIR/aurora_eval_metrics.json" \
    --tasks magicbrush ag something kubric whatsup  \
    2>&1 | tee "$LOG_DIR/eval_metrics.log"

  echo "AURORA quantitative evaluation completed"

  if [[ -n "${OPENAI_API_KEY:-}" ]]; then
    python src/evaluation/aurora/evaluate_aurora_gpt.py \
      --dataset_root "$DATASET_ROOT" \
      --generated_root "$GEN_DIR" \
      --split_file "$SPLIT_FILE" \
      --save_path "$OUTPUT_DIR/aurora_eval_metrics_gpt.json" \
      --model_name "${GPT_EVALUATOR}" \
      --tasks magicbrush ag something kubric whatsup  \
      2>&1 | tee "$LOG_DIR/eval_metrics_gpt.log"
    echo "AURORA GPT evaluation completed"
  else
    echo "OPENAI_API_KEY not set; skipping GPT-based evaluation."
  fi
else
  echo "Node $NODE_ID completed generation; evaluation handled by MASTER_NODE=$MASTER_NODE."
fi
